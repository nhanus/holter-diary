function revealHash() {
  for (const link of document.querySelectorAll('.language a')) {
    link.href = languageUrl(link.hreflang);
  }

  const target = document.getElementById(location.hash.slice(1));
  if (target?.tagName === 'DETAILS') target.open = true;
  if (target) requestAnimationFrame(() => target.scrollIntoView());
}

// Reopen a collapsed answer even when its fragment is already in the URL.
for (const link of document.querySelectorAll('a[href^="#question-"]')) {
  link.addEventListener('click', () => {
    const target = document.getElementById(link.hash.slice(1));
    if (target?.tagName === 'DETAILS') target.open = true;
  });
}
window.addEventListener('hashchange', revealHash);
revealHash();
